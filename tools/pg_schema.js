'use strict';
// Builds the Supabase/Postgres migration from RestoCore.SCHEMA, so the database always matches
// the tables and columns the app uses. The SQL is safe to run again: missing tables are created and
// missing columns added (columns are append-only, as with the Sheets tabs).
//   node tools/pg_schema.js         → after SCHEMA changes: a new dated migration file (nothing if unchanged),
//                                     then `npx supabase db push --remote`. Applied files are never edited.
//   node tools/pg_schema.js --init  → rewrite the newest file instead (only before it was ever pushed)
const fs = require('fs');
const path = require('path');

// Column types and keys are shared with the server (server/types.js).
const { COLUMN_TYPES, TABLE_TYPES, typeOf, keyOf } = require('../server/types.js');

const DATE_INDEX = ['Sales', 'StockMovements', 'Purchases', 'Expenses', 'DayCloses'];
const REF_INDEX = ['menuItemId', 'ingredientId', 'poId', 'invoiceId', 'channelId', 'prepId', 'promoId', 'ownerId'];
const q = (id) => '"' + id + '"';

function lockDown(table) {
  return `alter table ${q(table)} enable row level security;\n` +
    `revoke all on ${q(table)} from anon, authenticated;\n`;
}

/** The whole migration as SQL text (re-runnable). */
function buildSql(schema, textColumns) {
  const sqlType = (table, c) => (textColumns.includes(c) && !(TABLE_TYPES[table] || {})[c] ? 'text' : typeOf(table, c));
  const out = [
    '-- Restaurant Ops database (generated by tools/pg_schema.js from RestoCore.SCHEMA — do not edit by hand).',
    '-- Tables are only reachable through the "api" Edge Function: row level security is on with no policies,',
    '-- and the public API roles have no grants. Safe to run again.',
    '',
    "do $$ begin",
    "  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;",
    "  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;",
    "end $$;",
    '',
  ];
  Object.keys(schema).forEach((table) => {
    const cols = schema[table].map((c) => `  ${q(c)} ${sqlType(table, c)}`);
    cols.push('  "created_seq" bigserial');
    cols.push(`  primary key (${q(keyOf(table))})`);
    out.push(`create table if not exists ${q(table)} (\n${cols.join(',\n')}\n);`);
    // An older database gets the columns added since it was created.
    schema[table].forEach((c) => out.push(`alter table ${q(table)} add column if not exists ${q(c)} ${sqlType(table, c)};`));
    if (DATE_INDEX.includes(table)) out.push(`create index if not exists ${q(table + '_date')} on ${q(table)} (${q('date')});`);
    schema[table].filter((c) => REF_INDEX.includes(c)).forEach((c) => {
      out.push(`create index if not exists ${q(table + '_' + c)} on ${q(table)} (${q(c)});`);
    });
    out.push(lockDown(table));
  });
  out.push('create table if not exists "sessions" (\n  "key" text primary key,\n  "value" text not null,\n  "expires_at" timestamptz not null\n);');
  out.push('create index if not exists "sessions_expires" on "sessions" ("expires_at");');
  out.push(lockDown('sessions'));
  out.push('revoke all on all sequences in schema public from anon, authenticated;');
  return out.join('\n');
}

module.exports = { COLUMN_TYPES, TABLE_TYPES, typeOf, keyOf, buildSql };

if (require.main === module) {
  global.RestoCosting = require('../app/js/costing.js');
  global.RestoPricing = require('../app/js/pricing.js');
  const core = require('../app/js/core.js');
  const dir = process.env.MIGRATIONS_DIR || path.join(__dirname, '..', 'supabase', 'migrations');
  fs.mkdirSync(dir, { recursive: true });
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
  const sql = buildSql(core.SCHEMA, core.TEXT_COLUMNS);
  const newest = files.length ? path.join(dir, files[files.length - 1]) : null;
  if (newest && fs.readFileSync(newest, 'utf8').replace(/\r\n/g, '\n') === sql) {
    console.log('Schema unchanged; ' + path.basename(newest) + ' is current.');
    process.exit(0);
  }
  const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
  const file = process.argv.includes('--init') && newest ? newest : path.join(dir, `${stamp}_schema.sql`);
  fs.writeFileSync(file, sql);
  console.log('Wrote ' + path.relative(process.cwd(), file) + ' — next: npx supabase db push --remote');
}
