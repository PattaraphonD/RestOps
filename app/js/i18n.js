const DICTS = { en, th };

function detect() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved && DICTS[saved]) return saved;
  } catch { /* storage blocked */ }
  return (navigator.language || '').toLowerCase().startsWith('th') ? 'th' : 'en';
}

let lang = detect();

export function getLang() { return lang; }
export function setLang(code) {
  if (!DICTS[code]) return;
  lang = code;
  try { localStorage.setItem(KEY, code); } catch { /* ignore */ }
  document.documentElement.lang = code;
}
/** Intl locale for numbers and dates. Thai shows Buddhist-era years, as Thai users expect. */
export function locale() { return lang === 'th' ? 'th-TH' : 'en-US'; }

export function t(key, vars = {}) {
  const v = DICTS[lang][key] ?? en[key];
  if (v === undefined) return key;
  if (typeof v === 'function') return v(vars);
  return v.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
}

export function defaults(name, code = lang) { return DEFAULTS[code][name].slice(); }
